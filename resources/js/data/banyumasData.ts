export interface KecamatanData {
    id: string;
    nama: string;
    kode_kec: string;
    zona: 'bahaya' | 'waspada' | 'aman';
    
    // 1. Populasi Ternak & Unggas (ekor)
    ayam_potong: number;   // ekor
    ayam_petelur: number;  // ekor
    kambing: number;       // ekor
    kambing_perah?: number; // ekor (kambing perah Saanen, Sapera, PE)
    domba: number;         // ekor
    sapi_perah: number;    // ekor
    sapi_potong: number;   // ekor
    ayam_broiler?: number; // alias kompatibilitas
    ayam_layer?: number;   // alias kompatibilitas
    populasi_total?: number; // total populasi peternakan & unggas

    // 2. Produksi Peternakan (kg & liter)
    telur_ayam: number;     // kg (Telur Ayam)
    daging_ayam: number;    // kg (Daging Ayam)
    daging_sapi: number;    // kg (Daging Sapi)
    daging_kambing: number; // kg (Daging Kambing)
    daging_domba: number;   // kg (Daging Domba)
    susu_sapi: number;      // liter (Susu Sapi)
    susu_kambing: number;   // liter (Susu Kambing)
    susu_domba: number;     // liter (Susu Domba)
    susu_liter?: number;    // alias kompatibilitas
    produksi_total?: number; // akumulasi produksi pangan

    // 3. Penyakit & Wabah (kasus)
    pmk: number;            // kasus aktif PMK
    lsd: number;            // kasus aktif LSD
    kasus_total?: number;   // total kasus aktif PMK & LSD

    // 4. Fasilitas (unit)
    poskeswan: number;      // unit poskeswan/RPH
    rph?: number;           // unit RPH
    luas_hmt_ha?: number;   // ha kebun hijauan makanan ternak (HMT/pakan)
    fasilitas_total?: number; // total fasilitas peternakan

    lat: number;
    lng: number;
    last_updated: string;
}

