export function calculateQuantiles(dataList: KecamatanData[], metricKey: keyof KecamatanData): number[] {
    const values = dataList.map(item => Number(item[metricKey]) || 0).sort((a, b) => a - b);
    const n = values.length;
    if (n === 0) return [0, 0, 0, 0];

    const q1 = values[Math.floor(n * 0.2)];
    const q2 = values[Math.floor(n * 0.4)];
    const q3 = values[Math.floor(n * 0.6)];
    const q4 = values[Math.floor(n * 0.8)];

    return [q1, q2, q3, q4];
}

export function getClassLevel(value: number, quantiles: number[]): number {
    if (value <= quantiles[0]) return 1;
    if (value <= quantiles[1]) return 2;
    if (value <= quantiles[2]) return 3;
    if (value <= quantiles[3]) return 4;
    return 5;
}

